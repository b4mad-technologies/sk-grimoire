use serde_json::{json, Value};
use spellkave_validate::canonical_document_hash;

// keep(K4): document identities must match the compiler's JS UTF-16 ordering,
// escaping and safe-integer serialization, independent of Rust map order.
#[test]
fn nested_document_hash_matches_independent_node_vector() {
    let input = r#"{"z":9007199254740991,"a":[null,true,"quote\"\n\u0001\u001b",{"\ue000":2,"\ud800\udc00":1}]}"#;
    let value: Value = serde_json::from_str(input).unwrap();
    // Node crypto SHA-256 over recursive Object.keys(...).sort() and
    // JSON.stringify primitives; expected output is not generated by Rust.
    // Both U+0001 and U+001B pin C0 escaping, including lowercase hex.
    // Reproduce: node -e 'const c=v=>Array.isArray(v)?"["+v.map(c).join(",")+"]":v&&typeof v==="object"?"{"+Object.keys(v).sort().map(k=>JSON.stringify(k)+":"+c(v[k])).join(",")+"}":JSON.stringify(v);console.log("sha256:"+require("node:crypto").createHash("sha256").update(c(JSON.parse(process.argv[1]))).digest("hex"))' '{"z":9007199254740991,"a":[null,true,"quote\"\n\u0001\u001b",{"\ue000":2,"\ud800\udc00":1}]}'
    assert_eq!(
        canonical_document_hash(&value).unwrap(),
        "sha256:0f664d8ad1c7fbff40bc42f1dfd76ffc9551c45d2206c1bd55c05fd4ee6058f8"
    );
    let reordered: Value = serde_json::from_str(
        r#"{"a":[null,true,"quote\"\n\u0001\u001b",{"\ud800\udc00":1,"\ue000":2}],"z":9007199254740991}"#,
    )
    .unwrap();
    assert_eq!(
        canonical_document_hash(&value),
        canonical_document_hash(&reordered)
    );
    let mut changed = value.clone();
    changed["a"].as_array_mut().unwrap().swap(0, 1);
    assert_ne!(
        canonical_document_hash(&value),
        canonical_document_hash(&changed)
    );
}

// keep(K4): every caller shares the unsigned safe-integer boundary, recursively.
#[test]
fn invalid_numbers_are_rejected_at_every_nesting_depth() {
    for input in [
        "-1",
        "-0.0",
        "1.0",
        "1.5",
        "1e0",
        "9007199254740992",
        "18446744073709551615",
    ] {
        let number: Value = serde_json::from_str(input).unwrap();
        for value in [
            number.clone(),
            json!([number.clone()]),
            json!({"outer":[{"n":number}]}),
        ] {
            assert_eq!(
                canonical_document_hash(&value).unwrap_err(),
                "document number is not an unsigned JSON-safe integer",
                "{input} in {value}"
            );
        }
    }
    for value in [
        json!(0),
        json!(9_007_199_254_740_991_u64),
        json!({"n":[0,9_007_199_254_740_991_u64]}),
    ] {
        assert!(canonical_document_hash(&value).is_ok());
    }
}
