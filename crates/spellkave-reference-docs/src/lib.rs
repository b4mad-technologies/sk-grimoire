//! Renders the DSL grammar and the manifest format reference.
//!
//! The DSL page comes from `spellkave_dsl::dsl_reference()`, the manifest
//! page from `spellkave_schema::manifest_json_schema()` and its doc comments.
//! The few hand-written paragraphs live in this file, beside the code that
//! renders them. Run `cargo run --locked -p spellkave-reference-docs -- --write`
//! after a change to either source, and `-- --check` to find drift.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde_json::{Map, Value};

const BANNER: &str = "<!-- Generated by `cargo run --locked -p spellkave-reference-docs -- --write`. Do not edit by hand. -->";

/// The generated pages, as paths relative to the repository root.
pub const PAGES: [&str; 2] = ["docs/dsl-grammar.md", "docs/manifest-format.md"];

/// The repository root, found from this crate's manifest directory.
pub fn repository_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// Every generated page with its expected text.
pub fn pages() -> Vec<(&'static str, String)> {
    vec![(PAGES[0], dsl_grammar()), (PAGES[1], manifest_format())]
}

/// The pages whose file differs from the generated text.
pub fn drifted(root: &Path) -> Vec<&'static str> {
    pages()
        .into_iter()
        .filter(|(path, text)| std::fs::read_to_string(root.join(path)).ok().as_ref() != Some(text))
        .map(|(path, _)| path)
        .collect()
}

/// Writes every generated page below `root`.
pub fn write(root: &Path) -> std::io::Result<()> {
    for (path, text) in pages() {
        let path = root.join(path);
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir)?;
        }
        std::fs::write(path, text)?;
    }
    Ok(())
}

/// Escapes text for a Markdown table cell and joins its lines.
fn cell(text: &str) -> String {
    text.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('|', "\\|")
}

const DSL_HEAD: &str = r#"# DSL grammar

Manifest fields whose name ends in `_source` hold Spellkave DSL text: a
predicate (a guard that is true or false) or an outcome expression. This page
lists every operator of the language. The operator entries come from
`spellkave_dsl::dsl_reference()`. The parse gate
(`crates/spellkave-dsl/tests/reference_examples.rs`) runs every DSL example
through the parser, and the eval gate (`reference_examples_eval.rs`) checks
the documented result of each one.

## Operator precedence

**`||` binds tighter than `&&`.** This is the reverse of C, Rust and
JavaScript. `a && b || c` parses as `a && (b || c)`, and `a && b && c || d`
parses as `a && b && (c || d)`.

Boolean terms cannot be put in parentheses: `(` and `)` group integer
expressions only, so `(a && b) || c` is a parse error. Write the guard so
that the flat reading is the one you mean, or split it into separate
predicates. Avoid repeating a guard on both sides of `||`: the text
`act && niche && c || act && niche && d` parses as
`act && niche && (c || act) && niche && d`, which is true only when both
`act` and `d` hold.

The test `or_binds_tighter_than_and` in `crates/spellkave-dsl/tests/corpus.rs`
proves the rule. Whether to keep or flip it is open decision
`sk-jay0.7.105.10`.

## How to read an entry

Each operator has its AST name as heading. *Expression kind* says where it may
appear: in a predicate, in an outcome expression, or in both. *Returns* is the
value type it produces. An entry marked **Not DSL text** has no parser
surface: it is written as a structured `[[consequence_frame_writes]]` row,
and its example is that row's `frame_write` value (see
[the manifest format](manifest-format.md#consequence_frame_writes)).

## Operators
"#;

/// The DSL grammar page.
pub fn dsl_grammar() -> String {
    let (title, rest) = DSL_HEAD.split_once("\n\n").expect("head has a title");
    let mut out = format!("{title}\n\n{BANNER}\n\n{rest}");
    for op in spellkave_dsl::dsl_reference().operators {
        let returns = serde_json::to_value(op.returns).expect("value type serializes");
        let returns = returns.as_str().expect("value type is a string");
        let _ = write!(
            out,
            "\n### {}\n\nExpression kind: `{}`. Returns: `{returns}`.\n\n",
            op.operator, op.expression_kind
        );
        out.push_str(match op.authoring {
            "frame_write" => "**Not DSL text.** It has no parser surface and cannot appear in a `_source` field. The live write is a structured `[[consequence_frame_writes]]` row; the example below is that row's `frame_write` value.\n",
            _ => "Written as DSL text.\n",
        });
        if !op.args.is_empty() {
            out.push_str("\n| Arg | Shape |\n|---|---|\n");
            for arg in &op.args {
                let _ = writeln!(out, "| `{}` | {} |", arg.name, cell(arg.shape));
            }
        }
        if !op.notes.is_empty() {
            out.push('\n');
            for note in &op.notes {
                let _ = writeln!(out, "- {note}");
            }
        }
        if !op.examples.is_empty() {
            out.push_str("\nExamples:\n\n");
            for example in &op.examples {
                let _ = writeln!(out, "- `{example}`");
            }
        }
    }
    out
}

const MANIFEST_HEAD: &str = r#"# Manifest format

A Spellkave content bundle is a set of TOML manifests. This page lists the
top-level fields and every row kind a manifest may hold. It comes from
`spellkave_schema::manifest_json_schema()`; the descriptions are the doc
comments of `crates/spellkave-schema`. Fields whose name ends in `_source`
hold DSL text, described in [the DSL grammar](dsl-grammar.md).

## Required header

Every manifest starts with the schema line and the schema version.

```toml
#:schema https://spellkave.dev/schema/world-manifest-1.0.0.json
schema_version = "1.0.0"
```

## Applyset

A root manifest names the applyset it belongs to in the top-level field
`applyset`, right after the header:

```toml
applyset = "srd"
```

Only the root declares it. An `[[include]]` fragment that sets `applyset` is
rejected. How `sk diff` and `sk apply` use the applyset is described in the
`sk` command-line documentation of sk-sdk.
"#;

/// The manifest format page.
pub fn manifest_format() -> String {
    let schema = serde_json::to_value(spellkave_schema::manifest_json_schema())
        .expect("manifest schema serializes");
    let properties = schema["properties"]
        .as_object()
        .expect("schema has properties");
    let definitions = schema["definitions"]
        .as_object()
        .expect("schema has definitions");
    let required = string_set(&schema["required"]);

    let (title, rest) = MANIFEST_HEAD.split_once("\n\n").expect("head has a title");
    let mut out = format!("{title}\n\n{BANNER}\n\n{rest}");

    let mut rows = Vec::new();
    let mut top = Map::new();
    for (name, property) in properties {
        match row_definition(property) {
            Some(row) => rows.push((name, row)),
            None => {
                top.insert(name.clone(), property.clone());
            }
        }
    }

    out.push_str("\n## Top-level fields\n\n");
    field_table(&mut out, &top, &required);

    out.push_str("\n## Rows\n\nEach row kind is an array of tables: `[[name]]`.\n");
    for (name, row) in &rows {
        let definition = &definitions[*row];
        let _ = write!(out, "\n### {name}\n\n`[[{name}]]`, schema type `{row}`.\n");
        description(&mut out, definition);
        out.push('\n');
        field_table(
            &mut out,
            definition["properties"].as_object().unwrap_or(&Map::new()),
            &string_set(&definition["required"]),
        );
    }

    out.push_str("\n## Other types\n\nTypes that the fields above refer to.\n");
    let row_names: Vec<&str> = rows.iter().map(|(_, row)| *row).collect();
    for (name, definition) in definitions {
        if row_names.contains(&name.as_str()) {
            continue;
        }
        let _ = write!(out, "\n### {name}\n");
        description(&mut out, definition);
        if let Some(fields) = definition["properties"].as_object() {
            out.push('\n');
            field_table(&mut out, fields, &string_set(&definition["required"]));
        } else {
            let _ = writeln!(out, "\nType: {}.", type_of(definition));
        }
    }
    out
}

/// The definition name of a row kind: an array of `$ref` items.
fn row_definition(property: &Value) -> Option<&str> {
    if property["type"] != "array" {
        return None;
    }
    property["items"]["$ref"]
        .as_str()?
        .strip_prefix("#/definitions/")
}

fn string_set(value: &Value) -> Vec<&str> {
    value
        .as_array()
        .map(|items| items.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default()
}

fn description(out: &mut String, schema: &Value) {
    if let Some(text) = schema["description"].as_str() {
        let _ = write!(out, "\n{}\n", text.trim());
    }
}

fn field_table(out: &mut String, fields: &Map<String, Value>, required: &[&str]) {
    out.push_str("| Field | Required | Type | Default | Description |\n|---|---|---|---|---|\n");
    for (name, field) in fields {
        let default = match field.get("default") {
            Some(value) => format!("`{value}`"),
            None => String::new(),
        };
        let _ = writeln!(
            out,
            "| `{name}` | {} | {} | {} | {} |",
            if required.contains(&name.as_str()) {
                "yes"
            } else {
                "no"
            },
            cell(&type_of(field)),
            cell(&default),
            cell(field["description"].as_str().unwrap_or("")),
        );
    }
}

/// A short, readable type for a JSON schema.
fn type_of(schema: &Value) -> String {
    if let Some(reference) = schema["$ref"].as_str() {
        let name = reference.trim_start_matches("#/definitions/");
        return format!("[`{name}`](#{})", name.to_lowercase());
    }
    for combinator in ["allOf", "anyOf", "oneOf"] {
        if let Some(options) = schema[combinator].as_array() {
            let parts: Vec<String> = options.iter().map(type_of).collect();
            return parts.join(if combinator == "allOf" {
                " and "
            } else {
                " or "
            });
        }
    }
    if let Some(values) = schema["enum"].as_array() {
        let values: Vec<String> = values.iter().map(|value| format!("`{value}`")).collect();
        return format!("one of {}", values.join(", "));
    }
    let types: Vec<&str> = match &schema["type"] {
        Value::String(single) => vec![single.as_str()],
        Value::Array(many) => many.iter().filter_map(Value::as_str).collect(),
        _ => return "any value".to_owned(),
    };
    let parts: Vec<String> = types
        .into_iter()
        .map(|kind| match kind {
            "array" => format!("array of {}", type_of(&schema["items"])),
            "object" if schema["additionalProperties"].is_object() => {
                format!("table of {}", type_of(&schema["additionalProperties"]))
            }
            "string" if schema["pattern"].is_string() => {
                format!(
                    "string matching `{}`",
                    schema["pattern"].as_str().unwrap_or_default()
                )
            }
            other => format!("`{other}`"),
        })
        .collect();
    parts.join(" or ")
}
